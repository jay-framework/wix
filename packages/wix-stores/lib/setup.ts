const WIX_STORES_APP_DEF_ID = '215238eb-22a5-4c36-9e7b-e7c08025e04e';
const CATALOG_VERSION_URL = 'https://www.wixapis.com/stores/v3/provision/version';
const CATALOG_READY_TIMEOUT_MS = 60_000;
const CATALOG_POLL_INTERVAL_MS = 3_000;

const ADD_MENU_OUTPUT_REL = 'agent-kit/aiditor/add-menu/wix-stores.yaml';
const ADD_MENU_GENERATED_REL = 'agent-kit/aiditor/add-menu/wix-stores.generated.yaml';

function resolvePackageAgentKitPath(relativePath: string): string {
    const thisDir = path.dirname(fileURLToPath(import.meta.url));
    const fromDist = path.join(thisDir, relativePath);
    if (fs.existsSync(fromDist)) {
        return fromDist;
    }
    return path.join(thisDir, '..', relativePath);
}

function resolveAddMenuTemplatePath(): string {
    return resolvePackageAgentKitPath('agent-kit/aiditor/add-menu.template.yaml');
}

/**
 * Write Add Menu catalog from package template (Design Log #20 W1).
 * Idempotent: skips when output exists unless ctx.force.
 *
 * Q8 note: product-page prompt references agent-kit/materialized-contracts/wix-stores/product-page.jay-contract,
 * which is materialized by the existing wix-stores setup / agent-kit flow (not by this writer).
 */
function writeAddMenuCatalog(ctx: { projectRoot: string; force: boolean }): string | null {
    const outputPath = path.join(ctx.projectRoot, ADD_MENU_OUTPUT_REL);

    if (fs.existsSync(outputPath) && !ctx.force) {
        return null;
    }

    const templatePath = resolveAddMenuTemplatePath();
    const templateContent = fs.readFileSync(templatePath, 'utf-8');

    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, templateContent, 'utf-8');

    return ADD_MENU_OUTPUT_REL;
}

/**
 * Write generated Add Menu catalog — one item per indexed category (Design Log #19 M19.2).
 * Regenerated on every successful references run (jay-stack agent-kit).
 */
function writeGeneratedAddMenuCatalog(
    projectRoot: string,
    categoryRoots: CategoryTreeNode[],
): string {
    const outputPath = path.join(projectRoot, ADD_MENU_GENERATED_REL);
    const config = loadWixStoresConfig(projectRoot);
    const items = buildCategoryAddMenuItems(categoryRoots, config);

    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    const header =
        '# DO NOT EDIT BY HAND — regenerated by jay-stack agent-kit (wix-stores references)\n\n';
    const body = yaml.dump({ items }, { indent: 2, lineWidth: 120, noRefs: true });
    fs.writeFileSync(outputPath, header + body, 'utf-8');

    return ADD_MENU_GENERATED_REL;
}

const CONFIG_TEMPLATE = `# Wix Stores Configuration
#
# URL templates for link generation.
# Placeholders: {slug} (product), {category} (sub-category), {prefix} (root category)
#
# urls:
#   product: "/products/{slug}"                              # simple (default)
#   product: "/products/{category}/{slug}"                   # with categories
#   product: "/products/{prefix}/{category}/{slug}"          # with prefixes + categories
#   category: "/products/{prefix}/{category}"                # category deep-link pages
#
# Fallback category for pages without category context:
# defaultCategory: "all-products"
#
# Locale for prices (BCP 47; a Wix site's regional setting). Not set = the API's formatted amounts:
# locale: "ja-JP"
#
# Full reference: agent-kit/designer/store-configuration.md (materialized after jay-stack agent-kit)

urls:
  product: "/products/{slug}"
`;

function formatConfigIssues(issues: ConfigValidationIssue[]): string {
    if (issues.length === 0) {
        return '';
    }
    const lines = issues.map((issue) => {
        const label = issue.severity === 'error' ? 'Error' : 'Warning';
        const hint = issue.suggestion ? ` ${issue.suggestion}` : '';
        return `  - ${label}: ${issue.message}${hint}`;
    });
    return `\n\nConfig (${WIX_STORES_CONFIG_FILE_NAME}):\n${lines.join('\n')}`;
}

/** The V3 catalog check: null when the catalog answers, else the error message for setup. */
async function checkCatalog(wixClient: WixClientService): Promise<string | null> {
    try {
        await searchProductsApi(wixClient, {});
        return null;
    } catch (e: any) {
        const msg = e.message || '';
        const hint =
            msg.includes('404') || msg.includes('not found')
                ? 'Wix Stores may not be installed on this site'
                : msg.includes('428')
                  ? 'the Stores catalog is not ready yet (just installed?) — re-run setup in a minute'
                  : msg.includes('403') || msg.includes('permission')
                    ? 'the API key or app may lack Wix Stores permissions'
                    : 'This package requires the Stores Catalog V3 API — if using Catalog V1, use @jay-framework/wix-stores-v1 instead';
        return `Wix Stores V3 API check failed: ${hint}. (${msg})`;
    }
}

/** A fresh install answers the catalog APIs with 428 until the catalog is provisioned. */
async function waitForCatalog(siteToken: string): Promise<void> {
    const deadline = Date.now() + CATALOG_READY_TIMEOUT_MS;
    while (Date.now() < deadline) {
        const response = await fetch(CATALOG_VERSION_URL, {
            headers: { Authorization: siteToken, 'Content-Type': 'application/json' },
        });
        if (response.ok) {
            const data: { catalogVersion?: string } = await response.json();
            if (data.catalogVersion) {
                console.log(`[wix-stores] Catalog ready: ${data.catalogVersion}`);
                return;
            }
        }
        await new Promise((resolve) => setTimeout(resolve, CATALOG_POLL_INTERVAL_MS));
    }
    console.log('[wix-stores] Catalog not reported ready yet; continuing');
}

export async function setupWixStores(ctx: PluginSetupContext): Promise<PluginSetupResult> {
    if (ctx.initError) {
        return {
            status: 'error',
            message: `Service init failed (is wix-server-client configured?). ${ctx.initError.message}`,
        };
    }

    // The stores service is registered by this plugin's init, which runs only after this setup succeeds
    let wixClient: WixClientService;
    try {
        wixClient = getService(WIX_CLIENT_SERVICE);
    } catch {
        return {
            status: 'error',
            message: 'Wix client not available. Run setup for wix-server-client first.',
        };
    }

    // Create config template if it doesn't exist
    const configPath = path.join(ctx.configDir, WIX_STORES_CONFIG_FILE_NAME);
    const configCreated: string[] = [];

    if (!fs.existsSync(configPath)) {
        if (!fs.existsSync(ctx.configDir)) {
            fs.mkdirSync(ctx.configDir, { recursive: true });
        }
        fs.writeFileSync(configPath, CONFIG_TEMPLATE, 'utf-8');
        configCreated.push(`config/${WIX_STORES_CONFIG_FILE_NAME}`);
    }

    // Only a failing catalog needs the Wix user: installing Stores requires the Wix CLI login (DL #47)
    let catalogError = await checkCatalog(wixClient);
    if (catalogError && ctx.interactive) {
        try {
            const { status, siteToken } = await ensureSiteAppInstalled(
                ctx.projectRoot,
                WIX_STORES_APP_DEF_ID,
                { appName: 'Wix Stores', interactive: true },
            );
            if (status === 'installed') {
                configCreated.push('Wix Stores app');
                await waitForCatalog(siteToken);
                catalogError = await checkCatalog(wixClient);
            }
        } catch (e) {
            return {
                status: 'error',
                message: `Installing Wix Stores failed: ${e instanceof Error ? e.message : e}`,
            };
        }
    }
    if (catalogError) {
        return { status: 'error', message: catalogError };
    }

    const config = loadWixStoresConfig(ctx.projectRoot);
    let categorySlugs: Set<string> | undefined;

    if (config.defaultCategory) {
        try {
            categorySlugs = await fetchCategorySlugs(wixClient);
        } catch {
            // Best-effort: setup still succeeds when categories cannot be loaded.
        }
    }

    const configIssues = validateWixStoresConfigValue(config, { categorySlugs });
    const hasConfigErrors = configIssues.some((issue) => issue.severity === 'error');

    let message = `Wix Stores configured (product URL: ${config.urls.product})`;
    message += formatConfigIssues(configIssues);

    return {
        status: hasConfigErrors ? 'needs-config' : 'configured',
        message,
        ...(configCreated.length > 0 ? { configCreated } : {}),
    };
}

// ============================================================================
// References handler (jay-stack agent-kit) — generate category tree reference
// ============================================================================

interface CategoryNode extends CategoryTreeNode {}

/**
 * Generate a YAML reference file with the full category tree.
 * Shows all categories with IDs, names, product counts, and parent-child hierarchy.
 */
export async function generateWixStoresAgentKit(
    ctx: PluginAgentKitContext,
): Promise<PluginAgentKitResult> {
    if (ctx.initError) {
        throw new Error(`init failed: ${ctx.initError.message}`);
    }

    let storesService: WixStoresService;
    try {
        storesService = getService(WIX_STORES_SERVICE_MARKER) as WixStoresService;
    } catch {
        throw new Error('WixStoresService not available. Run jay-stack setup first.');
    }

    fs.mkdirSync(ctx.referencesDir, { recursive: true });

    const agentKitCreated: string[] = [];

    const addMenuStatic = writeAddMenuCatalog(ctx);
    if (addMenuStatic) {
        agentKitCreated.push(addMenuStatic);
    }
    agentKitCreated.push(
        ...copyAiditorAddMenuThumbnails(ctx, resolvePackageAgentKitPath, 'wix-stores'),
    );

    // Fetch all visible categories
    const allCategories: Array<{
        _id?: string;
        name?: string;
        slug?: string;
        itemCounter?: number;
        parentCategory?: { _id?: string };
    }> = [];

    let cursor: string | undefined;
    let hasMore = true;
    while (hasMore) {
        const result = await queryCategoriesApi(
            storesService.wixClient,
            cursor
                ? { cursorPaging: { cursor } }
                : { filter: { visible: true }, cursorPaging: { limit: 100 } },
        );
        allCategories.push(...(result.categories || []));
        cursor = result.pagingMetadata?.cursors?.next;
        hasMore = !!cursor;
    }

    // Build tree structure
    const nodeMap = new Map<string, CategoryNode>();
    for (const cat of allCategories) {
        if (!cat._id) continue;
        nodeMap.set(cat._id, {
            _id: cat._id,
            name: cat.name || '',
            slug: cat.slug || '',
            productCount: cat.itemCounter || 0,
            children: [],
        });
    }

    const roots: CategoryNode[] = [];
    for (const cat of allCategories) {
        if (!cat._id) continue;
        const node = nodeMap.get(cat._id)!;
        const parentId = cat.parentCategory?._id;
        if (parentId && nodeMap.has(parentId)) {
            nodeMap.get(parentId)!.children.push(node);
        } else {
            roots.push(node);
        }
    }

    // Write YAML
    const categoriesPath = path.join(ctx.referencesDir, 'categories.yaml');
    fs.writeFileSync(
        categoriesPath,
        yaml.dump(
            {
                _description:
                    'Wix Stores category tree for agent discovery. Shows category hierarchy, IDs, slugs, product counts, and parent-child relationships.',
                totalCategories: allCategories.length,
                categoryTree: roots,
            },
            { indent: 2, lineWidth: 120, noRefs: true },
        ),
        'utf-8',
    );

    const addMenuGenerated = writeGeneratedAddMenuCatalog(ctx.projectRoot, roots);

    // Fetch and write data extension schemas
    let extensionFieldCount = 0;
    try {
        const extensionSchemas = await storesService.getDataExtensionSchemas();
        const userFieldsSchema = extensionSchemas.find(
            (s: DataExtensionSchema) => s.namespace === '_user_fields',
        );
        const properties = userFieldsSchema?.jsonSchema?.properties as
            | Record<string, { type?: string }>
            | undefined;

        if (properties && Object.keys(properties).length > 0) {
            extensionFieldCount = Object.keys(properties).length;
            const extensionPath = path.join(ctx.referencesDir, 'data-extension-fields.yaml');
            fs.writeFileSync(
                extensionPath,
                yaml.dump(
                    {
                        _description:
                            'Product data extension fields (custom fields defined in Wix dashboard).',
                        fqdn: 'wix.stores.v3.product',
                        namespace: '_user_fields',
                        fieldCount: extensionFieldCount,
                        fields: Object.fromEntries(
                            Object.entries(properties).map(([key, prop]) => [
                                key,
                                { type: prop.type },
                            ]),
                        ),
                    },
                    { indent: 2, lineWidth: 120, noRefs: true },
                ),
                'utf-8',
            );
        }
    } catch (error) {
        console.error('[wix-stores] Failed to fetch data extension schemas:', error);
    }

    agentKitCreated.push(
        `agent-kit/references/${ctx.pluginName}/categories.yaml`,
        addMenuGenerated,
    );
    if (extensionFieldCount > 0) {
        agentKitCreated.push(`agent-kit/references/${ctx.pluginName}/data-extension-fields.yaml`);
    }

    return {
        agentKitCreated,
        message: `${allCategories.length} categories (${roots.length} root), ${extensionFieldCount} extension fields`,
    };
}
