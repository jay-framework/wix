/** The defaults with the site's overrides merged per key (never a whole table replaced). */
export interface ResolvedAddressLabels {
    partLabel(part: LayoutPart | 'country'): string;
    subdivisionPartLabel(country: CountryCode | undefined): string;
    subdivisionName(country: CountryCode, code: string): string;
}

export function resolveAddressLabels(config: AddressLabelsConfig = {}): ResolvedAddressLabels {
    const parts = { ...PART_LABELS, ...config.parts };
    const subdivisionParts = { ...SUBDIVISION_PART_LABELS, ...config.subdivisionPart };
    return {
        partLabel: (part) => parts[part],
        subdivisionPartLabel: (country) =>
            (country && subdivisionParts[country]) || parts.subdivision,
        subdivisionName: (country, code) =>
            config.subdivisions?.[country]?.[code] ?? SUBDIVISION_NAMES[country]?.[code] ?? code,
    };
}
